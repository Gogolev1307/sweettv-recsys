"""Frozen validation configurations and lossless Kaggle CSV writing/checks."""

from __future__ import annotations

import csv
import hashlib
import json
import re
from pathlib import Path

import pandas as pd

METHODS = ("popularity", "rewatch", "MF", "PPR", "CBF", "association", "hybrid")


def load_frozen_configurations(path: Path) -> tuple[dict, str]:
    """Read selected flags, never rank configurations or evaluate new scores."""
    frame = pd.read_csv(path, dtype={"selected": "boolean"})
    selected = frame.loc[frame.selected.fillna(False)]
    if set(selected.method) != set(METHODS) or selected.method.duplicated().any():
        raise ValueError("Expected one selected validation configuration for each method")
    if not selected.seed.eq(42).all() or not selected.evaluated_users.eq(1246).all():
        raise ValueError("Selected configurations do not match the frozen seed/cohort")
    configurations = {
        row.method: json.loads(row.hyperparameters) for row in selected.itertuples(index=False)
    }
    if configurations["MF"].get("seed") != 42:
        raise ValueError("The selected MF seed must be 42")
    return configurations, hashlib.sha256(path.read_bytes()).hexdigest()


def write_submission(path: Path, user_ids, predictions: dict[int, list[int]]) -> None:
    """Serialize Python integers directly; no float conversion or DataFrame inference."""
    users = tuple(map(int, user_ids))
    if set(predictions) != set(users):
        raise ValueError("Prediction users differ from the template cohort")
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["user_id", "tv_show_id"])
        for user in users:
            writer.writerow([str(user), " ".join(str(int(item)) for item in predictions[user])])


def write_or_preserve_submission(path: Path, user_ids, predictions) -> bool:
    """Never overwrite an existing CSV, even when regenerated bytes would match."""
    if path.exists():
        with path.open("r", encoding="utf-8", newline="") as handle:
            actual = list(csv.reader(handle))
        expected = [["user_id", "tv_show_id"]] + [
            [str(int(user)), " ".join(str(int(item)) for item in predictions[int(user)])]
            for user in user_ids
        ]
        if actual != expected:
            raise ValueError(f"Existing submission differs; refusing to overwrite {path.name}")
        return False
    write_submission(path, user_ids, predictions)
    return True


def snapshot_submissions(directory: Path, new_name: str) -> dict:
    return {
        path.name: {
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "mtime_ns": path.stat().st_mtime_ns, "size": path.stat().st_size,
        }
        for path in sorted(directory.glob("submission_*.csv")) if path.name != new_name
    }


def verify_preserved_submissions(directory: Path, snapshot: dict) -> None:
    for name, original in snapshot.items():
        path = directory / name
        if not path.exists():
            raise AssertionError(f"Earlier submission disappeared: {name}")
        current = {
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "mtime_ns": path.stat().st_mtime_ns, "size": path.stat().st_size,
        }
        if current != original:
            raise AssertionError(f"Earlier submission was modified: {name}")


def load_frozen_v2_configuration(path: Path) -> tuple[dict, str]:
    """Verify the already-selected strict-truth weights; never perform selection."""
    from src.hybrid import V2_SELECTION_RULE, days_weight_grid, strict_truth_mean

    manifest = json.loads(path.read_text())
    if manifest["seed"] != 42 or manifest["threshold_seconds"] != 300 or manifest["selection_rule"] != V2_SELECTION_RULE:
        raise ValueError("Invalid v2 seed, threshold or selection rule")
    if manifest["weights"] not in list(days_weight_grid()):
        raise ValueError("Frozen v2 weights are outside the specified validation grid")
    source = path.parent / manifest["validation_results_file"]
    if hashlib.sha256(source.read_bytes()).hexdigest() != manifest["validation_results_sha256"]:
        raise ValueError("The frozen v2 validation table has changed")
    frame = pd.read_csv(source, dtype={"selected": "boolean"})
    selected = frame.loc[frame.method.eq("hybrid_v2") & frame.selected.fillna(False)]
    if len(selected) != 1 or json.loads(selected.iloc[0].hyperparameters) != manifest["weights"]:
        raise ValueError("The v2 manifest does not match the selected validation row")
    if abs(float(selected.iloc[0].strict_mean_map_at_5) - manifest["strict_mean_map_at_5"]) > 1e-9:
        raise ValueError("Frozen v2 objective differs from the validation table")
    if abs(strict_truth_mean(manifest["validation_scores"]) - manifest["strict_mean_map_at_5"]) > 1e-12:
        raise ValueError("V2 selection objective must use T2, T3 and T4 only")
    legacy, legacy_digest = load_frozen_configurations(path.parent / "validation_methods.csv")
    if legacy_digest != manifest["legacy_config_sha256"] or manifest["component_configurations"] != {
        name: legacy[name] for name in ("MF", "PPR")
    }:
        raise ValueError("MF/PPR configurations differ from the original frozen selections")
    return manifest, hashlib.sha256(path.read_bytes()).hexdigest()


def load_frozen_v3_configuration(path: Path) -> tuple[dict, str]:
    """Read the frozen T2/T3-only selection and verify its component provenance."""
    from src.hybrid import V3_SELECTION_RULE, calibrated_truth_mean, habit_weight_grid

    manifest = json.loads(path.read_text())
    if manifest["seed"] != 42 or manifest["threshold_seconds"] != 300 or manifest["selection_rule"] != V3_SELECTION_RULE:
        raise ValueError("Invalid v3 seed, threshold or selection objective")
    if manifest["weights"] not in list(habit_weight_grid()):
        raise ValueError("V3 weights are outside the specified nonzero grid")
    if manifest["exposure_smoothing_days"] != 3 or manifest["target_schedule_fields"] != [
        "channel_id", "start_time", "duration", "tv_show_id"
    ]:
        raise ValueError("V3 availability features differ from validation")
    source = path.parent / manifest["validation_results_file"]
    if hashlib.sha256(source.read_bytes()).hexdigest() != manifest["validation_results_sha256"]:
        raise ValueError("The v3 validation table changed after weight freezing")
    frame = pd.read_csv(source, dtype={"selected": "boolean"})
    selected = frame.loc[frame.method.eq("hybrid_v3") & frame.selected.fillna(False)]
    if len(selected) != 1 or json.loads(selected.iloc[0].hyperparameters) != manifest["weights"]:
        raise ValueError("V3 manifest and selected validation row differ")
    if abs(float(selected.iloc[0].selection_mean_T2_T3) - manifest["selection_mean_T2_T3"]) > 1e-9:
        raise ValueError("V3 objective differs from the selected validation row")
    if abs(calibrated_truth_mean(manifest["validation_scores"]) - manifest["selection_mean_T2_T3"]) > 1e-12:
        raise ValueError("V3 must select using T2 and T3 only")
    legacy, legacy_digest = load_frozen_configurations(path.parent / "validation_methods.csv")
    if legacy_digest != manifest["legacy_config_sha256"] or manifest["component_configurations"] != {
        name: legacy[name] for name in ("MF", "PPR")
    }:
        raise ValueError("Frozen MF/PPR configurations changed")
    _, v2_digest = load_frozen_v2_configuration(path.parent / "hybrid_v2_selected.json")
    if v2_digest != manifest["v2_selection_manifest_sha256"]:
        raise ValueError("The calibrated frozen v2 baseline changed")
    return manifest, hashlib.sha256(path.read_bytes()).hexdigest()


def load_frozen_v4_configuration(path: Path) -> tuple[dict, str]:
    """Verify the TK-selected completion configuration without any new tuning."""
    from src.hybrid import COMPLETION_K_VALUES, V4_SELECTION_RULE, competition_truth_score, completion_weight_grid
    from src.truths import COMPETITION_GROUND_TRUTH_QUOTE

    manifest = json.loads(path.read_text())
    if manifest["seed"] != 42 or manifest["history_threshold_seconds"] != 300 or manifest["selection_rule"] != V4_SELECTION_RULE:
        raise ValueError("Invalid v4 seed, shared history rule or TK selection rule")
    if manifest["configuration"] not in list(completion_weight_grid()) or manifest["score80_coefficient"] != 1:
        raise ValueError("V4 configuration is outside the specified completion grid")
    if manifest["screen_time_percentages"] != [80, 50] or manifest["completion_requires_300_seconds"] is not False:
        raise ValueError("V4 completion thresholds differ from validation")
    if manifest["competition_ground_truth_quote"] != COMPETITION_GROUND_TRUTH_QUOTE:
        raise ValueError("V4 ground-truth provenance differs from validation")
    if manifest["target_schedule_fields"] != ["channel_id", "start_time", "duration", "tv_show_id"]:
        raise ValueError("V4 target availability schema changed")
    if manifest["best_standalone_score80_k"] not in COMPLETION_K_VALUES:
        raise ValueError("Standalone completion k is outside the specified grid")
    source = path.parent / manifest["validation_results_file"]
    if hashlib.sha256(source.read_bytes()).hexdigest() != manifest["validation_results_sha256"]:
        raise ValueError("The v4 validation table changed after configuration freezing")
    frame = pd.read_csv(source, dtype={"selected": "boolean"})
    selected = frame.loc[frame.method.eq("hybrid_v4") & frame.selected.fillna(False)]
    if len(selected) != 1 or json.loads(selected.iloc[0].hyperparameters) != manifest["configuration"]:
        raise ValueError("V4 manifest and selected validation row differ")
    if abs(float(selected.iloc[0].selection_map_TK) - manifest["selection_map_TK"]) > 1e-9:
        raise ValueError("Frozen v4 objective differs from the selected table row")
    if abs(competition_truth_score(manifest["validation_scores"]) - manifest["selection_map_TK"]) > 1e-12:
        raise ValueError("V4 selection must use TK only")
    legacy, legacy_digest = load_frozen_configurations(path.parent / "validation_methods.csv")
    if legacy_digest != manifest["legacy_config_sha256"] or manifest["component_configurations"] != {"PPR": legacy["PPR"]}:
        raise ValueError("The original frozen PPR configuration changed")
    _, v3_digest = load_frozen_v3_configuration(path.parent / "hybrid_v3_selected.json")
    if v3_digest != manifest["v3_selection_manifest_sha256"]:
        raise ValueError("The frozen v3 calibration baseline changed")
    return manifest, hashlib.sha256(path.read_bytes()).hexdigest()


def validate_submission(path: Path, user_ids, candidates, cold_users, popularity_top_five) -> dict:
    """Validate the written text, including canonical uint64 decimal spelling."""
    users = tuple(map(int, user_ids))
    pool, cold = set(map(int, candidates)), set(map(int, cold_users))
    if not cold.issubset(users):
        raise ValueError("Cold-start users are outside the template cohort")
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.reader(handle)
        if next(reader, None) != ["user_id", "tv_show_id"]:
            raise ValueError("Incorrect submission header")
        rows = list(reader)
    if len(rows) != len(users) or any(len(row) != 2 for row in rows):
        raise ValueError("Incorrect submission row count or column count")
    if any(not re.fullmatch(r"[0-9]+", row[0]) or row[0] != str(int(row[0])) for row in rows):
        raise ValueError("User ids must be plain canonical integers")
    if [row[0] for row in rows] != [str(user) for user in users]:
        raise ValueError("User order differs from the template")
    for user, (_, text) in zip(users, rows):
        if not re.fullmatch(r"[1-9][0-9]*(?: [1-9][0-9]*){4}", text):
            raise ValueError("Expected five space-separated positive integer programme ids")
        items = list(map(int, text.split(" ")))
        if len(set(items)) != 5:
            raise ValueError("Programme ids must be distinct")
        if 0 in items or not set(items).issubset(pool):
            raise ValueError("Programme outside the labelled test candidate pool")
        if user in cold and items != list(popularity_top_five):
            raise ValueError("Cold-start fallback differs from fitting-window popularity")
    return {
        "rows": len(rows), "header": True, "user_order": True, "plain_integer_user_ids": True,
        "five_distinct_ids": True, "space_separated_integer_ids": True, "test_candidates": True,
        "no_zero": True, "cold_start_fallback_users": len(cold),
    }
